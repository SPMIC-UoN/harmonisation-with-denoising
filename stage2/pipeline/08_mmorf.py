#!/usr/bin/env python3
"""
08_mmorf.py - H3a: MMORF (FSL 6.0.7.18, mmorf v0.4.2, CUDA) registration of each session's
template-space data to MNI152 using the Table S1 references (MNI152_T1_1mm_brain, FSL_HCP1065_FA_1mm,
FSL_HCP1065_tensor_1mm), then FA on the FSL MNI152 2 mm grid and the checkerboard WM mask.

Once: H3a WM mask on the MNI 2 mm grid (FAST on MNI152, PVE >= 0.5, 1-in-8 lattice; Section 3.6).
Per template (shared by arms and sessions):
  flirt -dof 12 T_template0 -> MNI152_T1_1mm_brain       (affine initialisation, FSL 6.0.6.4)
Per arm x session (mode "session"):
  mmorf with three modalities:
    T1w     ref MNI152_T1_1mm_brain     mov T_template0
    FA      ref FSL_HCP1065_FA_1mm      mov fits/<arm>/<ses>/all/dti_b0b1000_FA
    tensor  ref FSL_HCP1065_tensor_1mm  mov fits/<arm>/<ses>/all/dti_b0b1000_tensor
  (masks and bias estimation follow mmorf_params.json; off in the FSL example it is based on)
  convertwarp (affine + MMORF warp) and applywarp of FA (spline) onto MNI152_T1_2mm; the missing
  mask is warped too (trilinear, > 0 = missing) -> FA_MNI2mm_valid (NaN where missing).
--scalars-only: FA, MD (b0+b1000) and MK (all shells) with the same combined warp; invalid source voxels
  (for MK also MK <= 0 or > 3 in either arm) and voxels outside the brain mask set to 0 first; spline, no
  threshold; invalid masks warped trilinearly (> 0 = missing).
--mni-nonpos: per session and metric, missing in BOTH arms if non-positive or missing in either
  arm -> {FA,MD,MK}_MNI2mm_valid (overwrites the registration stage's FA_MNI2mm_valid).
MMORF parameters come from mmorf_params.json; production runs are refused unless its status is
"approved". Each MMORF run gets a GPU instance from a local allocation wrapper (GETGPU below; adapt to your system).
The fitted maps are resampled, never inspected here (blinding).
"""
