def affine_to_omm(t: Path) -> Path:
    mat = t / "T_to_MNI152_affine.mat"
    if not mat.is_file():
        run(f"flirt -in {t}/T_template0 -ref {REF_T1} -dof 12 -omat {mat}", t / "08_mmorf.log", FSL6)
    return mat


def register(arm: str, sub: str, ses: str, a, p: dict) -> dict:
    t = a.templates_dir / sub / "all"
    fit = a.fits_dir / arm / f"{sub}_{ses}" / "all"
    out = a.out_dir / arm / f"{sub}_{ses}"
    status = out / "status.json"
    if status.is_file() and json.loads(status.read_text()).get("state") == "done" and not a.force:
        return {"key": f"{arm}/{sub}_{ses}", "state": "skipped (done)"}
    out.mkdir(parents=True, exist_ok=True)
    log = out / "08_mmorf.log"
    miss = a.fits_dir / "_missing" / f"{sub}_{ses}" / "all" / "missing_metric_FA.nii.gz"
    need = [t / "T_template0.nii.gz", t / "T_template0_brainmask_1mm.nii.gz", t / "T_template0_brainmask_2mm.nii.gz",
            fit / "dti_b0b1000_FA.nii.gz", fit / "dti_b0b1000_tensor.nii.gz", miss]
    missing = [str(n) for n in need if not n.is_file()]
    if missing:
        return {"key": f"{arm}/{sub}_{ses}", "state": "blocked", "missing": missing}
    t0 = time.time()
    try:
        aff = affine_to_omm(t)
        cfg = out / "mmorf_config.ini"
        cfg.write_text(ini(p, t, Path(str(REF_MASK) + ".nii.gz"), t / "T_template0_brainmask_1mm.nii.gz",
                           t / "T_template0_brainmask_2mm.nii.gz", aff, fit / "dti_b0b1000_FA.nii.gz",
                           fit / "dti_b0b1000_tensor.nii.gz", out))
        run(f"export CUDA_VISIBLE_DEVICES=$({GETGPU})\necho \"GPU: $CUDA_VISIBLE_DEVICES\"\n"
            f"mmorf --version --config {cfg}", log, FSL7)
        run(f"convertwarp --ref={MNI2} --premat={aff} --warp1={out}/mmorf_warp --out={out}/T_to_MNI_combined_warp "
            f"--relout\n"
            f"applywarp --in={fit}/dti_b0b1000_FA --ref={MNI2} --warp={out}/T_to_MNI_combined_warp --interp=spline "
            f"--out={out}/FA_MNI2mm\nfslmaths {out}/FA_MNI2mm -thr 0 {out}/FA_MNI2mm\n"
            f"applywarp --in={miss} --ref={MNI2} --warp={out}/T_to_MNI_combined_warp --interp=trilinear "
            f"--out={out}/missing_MNI2mm", log, FSL6)
        # an MNI voxel touched by any missing template voxel is missing
        img = nib.load(str(out / "FA_MNI2mm.nii.gz"))
        fa = np.asarray(img.dataobj, dtype=np.float32).copy()
        missing = np.asarray(nib.load(str(out / "missing_MNI2mm.nii.gz")).dataobj) > 0
        fa[missing] = np.nan
        hdr = img.header.copy()
        hdr.set_data_dtype(np.float32)
        nib.save(nib.Nifti1Image(fa, img.affine, hdr), str(out / "FA_MNI2mm_valid.nii.gz"))
        ok = img.header.get_data_shape()[:3] == (91, 109, 91)
        st = {"state": "done" if ok else "failed", "params_status": p["status"], "runtime_min": round((time.time() - t0) / 60, 1),
              "finished": utcnow(), "generated_by": f"08_mmorf.py v{SCRIPT_VERSION}"}
    except Exception as exc:  # noqa: BLE001 - recorded
        st = {"state": "failed", "error": str(exc), "finished": utcnow()}
    status.write_text(json.dumps(st, indent=2))
    return {"key": f"{arm}/{sub}_{ses}", **st}


MK_RANGE = (0.0, 3.0)        # MK valid iff 0 < MK <= 3
SCALARS = {"FA": ("dti_b0b1000_FA", "missing_metric_FA", "missing_MNI2mm"),
           "MD": ("dti_b0b1000_MD", "missing_metric_MD", "missing_MD_MNI2mm"),
           "MK": ("dki_allshells_kurt", "missing_metric_MK", "missing_MK_MNI2mm")}


def warp_scalars(arm: str, sub: str, ses: str, a) -> dict:
    """FA, MD and MK onto the MNI 2 mm grid with the session's existing combined warp. Before the spline,
    invalid source voxels and everything outside the template brain mask are set to 0; invalid = missing for
    FA/MD, and missing OR MK <= 0 OR MK > 3 in either arm (within the brain) for MK. The invalid mask is
    warped trilinearly (> 0 = any contribution from an invalid source voxel -> missing in mni_nonpos). For MK the
    per-arm MK-range triggers are warped too (counts only). No new registration; no threshold after warping."""
    fits = {x: a.fits_dir / x / f"{sub}_{ses}" / "all" for x in ("nondenoised", "denoised")}
    fit = fits[arm]
    out = a.out_dir / arm / f"{sub}_{ses}"
    key = f"{arm}/{sub}_{ses}"
    st_p = out / "scalars_status.json"
    if st_p.is_file() and json.loads(st_p.read_text()).get("state") == "done" and not a.force:
        return {"key": key, "state": "skipped (done)"}
    reg = out / "status.json"
    if not reg.is_file() or json.loads(reg.read_text()).get("state") != "done":
        return {"key": key, "state": "blocked", "reason": "MMORF registration not done"}
    log = out / "08_mmorf_scalars.log"
    t0 = time.time()
    lo, hi = MK_RANGE
    try:
        bimg = nib.load(str(a.templates_dir / sub / "all" / "T_template0_brainmask_2mm.nii.gz"))
        brain = np.asarray(bimg.dataobj) > 0
        tmp = []

        def save(arr, name):
            p = out / f"_{name}.nii.gz"
            hdr = bimg.header.copy(); hdr.set_data_dtype(np.float32); hdr.set_slope_inter(1, 0)
            nib.save(nib.Nifti1Image(np.asarray(arr, np.float32), bimg.affine, hdr), str(p))
            tmp.append(p)
            return p

        for name, (src, mname, mout) in SCALARS.items():
            d41 = np.asarray(nib.load(str(a.fits_dir / "_missing" / f"{sub}_{ses}" / "all" / f"{mname}.nii.gz")).dataobj) > 0
            img = nib.load(str(fit / f"{src}.nii.gz"))
            if img.shape[:3] != brain.shape or not np.allclose(img.affine, bimg.affine, atol=1e-4):
                raise RuntimeError(f"{src}: grid differs from the template brain mask")
            v = np.asarray(img.dataobj, dtype=np.float64)
            invalid = d41.copy()
            warps = {}
            if name == "MK":
                trig = {}
                for x, f in fits.items():
                    w = np.asarray(nib.load(str(f / f"{src}.nii.gz")).dataobj, dtype=np.float64)
                    trig[x] = brain & ~d41 & (~np.isfinite(w) | (w <= lo) | (w > hi))
                invalid |= trig["nondenoised"] | trig["denoised"]
                warps.update({f"trigMK_{x}_MNI2mm": save(trig[x], f"trig_{x}") for x in trig})
            filled = np.where(brain & ~invalid & np.isfinite(v), v, 0.0)
            warps_cmd = [f"applywarp --in={save(filled, name + '_filled')} --ref={MNI2} "
                         f"--warp={out}/T_to_MNI_combined_warp --interp=spline --out={out}/{name}_MNI2mm",
                         f"applywarp --in={save(invalid, name + '_invalid')} --ref={MNI2} "
                         f"--warp={out}/T_to_MNI_combined_warp --interp=trilinear --out={out}/{mout}"]
            warps_cmd += [f"applywarp --in={pth} --ref={MNI2} --warp={out}/T_to_MNI_combined_warp --interp=trilinear "
                          f"--out={out}/{o}" for o, pth in warps.items()]
            run("\n".join(warps_cmd), log, FSL6)
        for p in tmp:
            p.unlink()
        st = {"state": "done", "runtime_s": round(time.time() - t0), "finished": utcnow(),
              "generated_by": f"08_mmorf.py v{SCRIPT_VERSION}"}
    except Exception as exc:  # noqa: BLE001 - recorded
        st = {"state": "failed", "error": str(exc), "finished": utcnow()}
    st_p.write_text(json.dumps(st, indent=2))
    return {"key": key, **st}


MNI_METRICS = {"FA": ("FA_MNI2mm", "missing_MNI2mm"), "MD": ("MD_MNI2mm", "missing_MD_MNI2mm"),
               "MK": ("MK_MNI2mm", "missing_MK_MNI2mm")}


def mni_nonpos(sub: str, ses: str, a) -> dict:
    """per session and metric, an MNI voxel is missing in BOTH arms if, in either
    arm, it is non-positive (or non-finite) after the spline warp or the warped missing mask is > 0. Writes
    {FA,MD,MK}_MNI2mm_valid (NaN where missing) identically masked in both arms; counts are arm-combined."""
    key = f"{sub}_{ses}"
    outs = {arm: a.out_dir / arm / key for arm in ("nondenoised", "denoised")}
    for arm, o in outs.items():
        st = json.loads((o / "scalars_status.json").read_text()) if (o / "scalars_status.json").is_file() else {}
        if st.get("state") != "done":
            return {"key": key, "state": "blocked", "reason": f"{arm}: scalars not done"}
    lat = np.asarray(nib.load(str(a.out_dir / "MNI152_2mm_wm_checkerboard-lattice.nii.gz")).dataobj) > 0
    counts = {}
    try:
        for m, (vname, mname) in MNI_METRICS.items():
            v, miss_d41, img = {}, {}, {}
            for arm, o in outs.items():
                img[arm] = nib.load(str(o / f"{vname}.nii.gz"))
                v[arm] = np.asarray(img[arm].dataobj, dtype=np.float32)
                miss_d41[arm] = np.asarray(nib.load(str(o / f"{mname}.nii.gz")).dataobj) > 0
            d41 = miss_d41["nondenoised"] | miss_d41["denoised"]
            nonpos = ~(np.isfinite(v["nondenoised"]) & np.isfinite(v["denoised"]) &
                       (v["nondenoised"] > 0) & (v["denoised"] > 0))
            missing = d41 | nonpos
            for arm, o in outs.items():
                x = v[arm].copy()
                x[missing] = np.nan
                hdr = img[arm].header.copy()
                hdr.set_data_dtype(np.float32)
                nib.save(nib.Nifti1Image(x, img[arm].affine, hdr), str(o / f"{m}_MNI2mm_valid.nii.gz"))
            counts[m] = {"wm_checkerboard_missing": int((missing & lat).sum()),
                         "wm_checkerboard_missing_invalid_mask": int((d41 & lat).sum()),
                         "wm_checkerboard_missing_nonpos_only": int((nonpos & ~d41 & lat).sum())}
            if m == "MK":                                        # MK-range triggers (warped by either arm's warp)
                tr = {x: np.zeros(lat.shape, bool) for x in outs}
                for x in outs:
                    for o in outs.values():
                        tr[x] |= np.asarray(nib.load(str(o / f"trigMK_{x}_MNI2mm.nii.gz")).dataobj) > 0
                tn, td = tr["nondenoised"] & lat, tr["denoised"] & lat
                counts[m]["d56_trigger"] = {"nondenoised_only": int((tn & ~td).sum()),
                                            "denoised_only": int((~tn & td).sum()), "both": int((tn & td).sum())}
        st = {"state": "done", "arms_combined": True, "wm_checkerboard_voxels": int(lat.sum()), "counts": counts,
              "finished": utcnow(), "generated_by": f"08_mmorf.py v{SCRIPT_VERSION}"}
    except Exception as exc:  # noqa: BLE001 - recorded
        st = {"state": "failed", "error": str(exc), "finished": utcnow()}
    d = a.out_dir / "_nonpos"
    d.mkdir(exist_ok=True)
    (d / f"{key}.json").write_text(json.dumps(st, indent=2))
    return {"key": key, **st}


def mni_wm_mask(out_dir: Path) -> None:
    """H3a WM mask (Section 3.6): FAST on MNI152_T1_1mm_brain, WM PVE >= 0.5 on the FSL MNI152 2 mm grid,
    then the sparse checkerboard (i, j, k all even; 1 in 8) and the dense one (1 in 2, Table S18). Written to <out>/MNI152_2mm_*."""
    wm = out_dir / "MNI152_2mm_wm.nii.gz"
    if not wm.is_file():
        run(f"""cd {out_dir}
fast -t 1 -n 3 -o MNI152_T1_1mm_brain_fast {FSL6}/data/standard/MNI152_T1_1mm_brain
flirt -in MNI152_T1_1mm_brain_fast_pve_2 -ref {MNI2} -applyxfm -init {FSL6}/etc/flirtsch/ident.mat -interp trilinear \\
    -out MNI152_2mm_wmpve
fslmaths MNI152_2mm_wmpve -thr 0.5 -bin MNI152_2mm_wm -odt char""", out_dir / "08_mmorf_mni_wm.log", FSL6)
    ref = nib.load(str(MNI2) + ".nii.gz")
    w = np.asarray(nib.load(str(wm)).dataobj) > 0
    i, j, k = np.meshgrid(*(np.arange(n) for n in w.shape), indexing="ij")
    lattice = (i % 2 == 0) & (j % 2 == 0) & (k % 2 == 0)
    parity = (i + j + k) % 2 == 0
    hdr = ref.header.copy()
    hdr.set_data_dtype(np.uint8)
    for name, arr in (("checkerboard-lattice", lattice), ("wm_checkerboard-lattice", w & lattice),
                      ("checkerboard-parity", parity), ("wm_checkerboard-parity", w & parity)):
        nib.save(nib.Nifti1Image(arr.astype(np.uint8), ref.affine, hdr), str(out_dir / f"MNI152_2mm_{name}.nii.gz"))
    (out_dir / "MNI152_2mm_wm_counts.json").write_text(json.dumps(
        {"wm_voxels": int(w.sum()), "wm_lattice_voxels": int((w & lattice).sum()),
         "wm_parity_voxels": int((w & parity).sum()), "created": utcnow()}, indent=2))


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description="H3a MMORF registration to MNI152 (Table S1: MNI152 T1, HCP1065 FA and tensor).")
    ap.add_argument("--deriv-dir", type=Path, required=True)
    ap.add_argument("--meta-dir", type=Path, required=True)
    ap.add_argument("--templates-dir", type=Path)
    ap.add_argument("--fits-dir", type=Path)
    ap.add_argument("--out-dir", type=Path)
    ap.add_argument("--params", type=Path, default=Path(__file__).resolve().parent / "mmorf_params.json")
    ap.add_argument("--allow-example-params", action="store_true", help="Testing only")
    ap.add_argument("--arms", nargs="+", default=["nondenoised", "denoised"])
    ap.add_argument("--sessions", nargs="+")
    ap.add_argument("--gpu-jobs", type=int, default=2)
    ap.add_argument("--force", action="store_true")
    ap.add_argument("--scalars-only", action="store_true",
                    help="warp MD and MK with the existing combined warps (no registration)")
    ap.add_argument("--jobs", type=int, default=8, help="parallel CPU jobs for --scalars-only")
    ap.add_argument("--mni-mask-only", action="store_true", help="(re)write the H3a MNI WM checkerboard mask and exit")
    ap.add_argument("--mni-nonpos", action="store_true",
                    help="per session, non-positive or missing in either arm -> missing in both (*_MNI2mm_valid)")
    a = ap.parse_args(argv)
    a.templates_dir = a.templates_dir or a.deriv_dir / "templates"
    a.fits_dir = a.fits_dir or a.deriv_dir / "fits"
    a.out_dir = a.out_dir or a.deriv_dir / "mmorf"
    p = json.loads(a.params.read_text())
    if p.get("status") != "approved" and not a.allow_example_params:
        print(f"{a.params}: status is '{p.get('status')}'. Set the Table S1 MMORF parameters and status 'approved' "
              ", or use --allow-example-params for testing.", file=sys.stderr)
        return 2
    for f in (REF_T1, REF_FA, REF_TENSOR, REF_MASK):
        if not Path(str(f) + ".nii.gz").is_file():
            print(f"missing {f}.nii.gz", file=sys.stderr)
            return 2
    a.out_dir.mkdir(parents=True, exist_ok=True)
    mni_wm_mask(a.out_dir)
    if a.mni_mask_only:
        print((a.out_dir / "MNI152_2mm_wm_counts.json").read_text())
        return 0
    rows = list(csv.DictReader(open(a.meta_dir / "sessions_manifest.csv", newline="")))
