def utcnow() -> str:
    return dt.datetime.now(dt.timezone.utc).isoformat(timespec="seconds")


def sha256_of(p: Path) -> str:
    h = hashlib.sha256()
    with open(p, "rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 22), b""):
            h.update(chunk)
    return h.hexdigest()


def run(cmds: str, log: Path, fsldir: Path, extra_env: dict | None = None) -> None:
    env = dict(os.environ, FSLDIR=str(fsldir), FSLOUTPUTTYPE="NIFTI_GZ",
               PATH=f"{fsldir}/share/fsl/bin:{fsldir}/bin:" + os.environ.get("PATH", ""), **(extra_env or {}))
    with open(log, "a") as fh:
        fh.write(f"\n### {utcnow()} FSLDIR={fsldir}\n")
        fh.flush()
        rc = subprocess.run(["bash", "-c", "set -e -o pipefail\nset -x\n" + cmds], stdout=fh, stderr=subprocess.STDOUT,
                            env=env).returncode
    if rc:
        raise RuntimeError(f"commands failed ({rc}); see {log}")


